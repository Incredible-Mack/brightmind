export function getAgeGroup(age?: number): AgeGroup {
  if (!age || age <= 5) return '0-5'
  if (age <= 8) return '6-8'
  if (age <= 11) return '9-11'
  return '12-14'
}

export function normalizeAgeGroups(raw: unknown): AgeGroup[] {
  if (Array.isArray(raw)) return raw as AgeGroup[]
  if (typeof raw === 'string') {
    try {
      const parsed = JSON.parse(raw)
      if (Array.isArray(parsed)) return parsed as AgeGroup[]
    } catch {}
    return [raw as AgeGroup]
  }
  return ['0-5', '6-8']
}

export function lessonMatchesAge(lesson: Lesson, targetAge: AgeGroup | 'all'): boolean {
  if (targetAge === 'all') return true
  const groups = normalizeAgeGroups(lesson.age_groups)
  return groups.includes(targetAge)
}

